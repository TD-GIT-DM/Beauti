function p(id, name, brand, description, imageUrl, price, tags, promoCodes, dealScore, availability = "in_stock", restock = null) {
  return { id, name, brand, description, imageUrl, price, tags, promoCodes, dealScore, availability, restock };
}

function sqlStr(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

function sqlJson(value) {
  return sqlStr(JSON.stringify(value));
}

// Avoid `?` in product_url — D1 exec treats ? as bind placeholders.
function productRow(item) {
  return `(
  ${sqlStr(item.id)},
  ${sqlStr(item.name)},
  ${sqlStr(item.brand)},
  ${sqlStr(item.description)},
  ${sqlStr(imageFor(item.id, item.imageUrl))},
  ${item.price.toFixed(2)}, 'USD',
  ${sqlStr(productUrlFor(item))},
  ${sqlJson(item.tags)},
  ${sqlJson(item.promoCodes)},
  ${item.dealScore}, ${sqlStr(item.availability)}, ${item.restock ? sqlStr(item.restock) : "NULL"},
  datetime('now'), datetime('now')
)`;
}

