function hasTokens(product, q) {
  const tokens = q.toLowerCase().split(/[^a-z0-9+%]+/).filter(Boolean);
  const hay = `${product.name} ${product.brand} ${product.description} ${product.tags.join(" ")}`.toLowerCase();
  return tokens.every((t) => hay.includes(t));
}

