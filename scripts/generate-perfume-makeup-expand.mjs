function sqlStr(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

function sqlJson(value) {
  return sqlStr(JSON.stringify(value));
}

function productRow(item) {
  return `(
  ${sqlStr(item.id)},
  ${sqlStr(item.name)},
  ${sqlStr(item.brand)},
  ${sqlStr(item.description)},
  ${sqlStr(item.imageUrl)},
  ${item.price.toFixed(2)}, 'USD',
  ${sqlStr(`https://www.sephora.com/product/${item.id}`)},
  ${sqlJson(item.tags)},
  ${sqlJson(item.promoCodes)},
  ${item.dealScore}, ${sqlStr(item.availability)}, ${item.restock ? sqlStr(item.restock) : "NULL"},
  datetime('now'), datetime('now')
)`;
}

const BATCH = 12;
const insertChunks = [];
for (let i = 0; i < products.length; i += BATCH) {
  insertChunks.push(`INSERT OR IGNORE INTO products (
  id, name, brand, description, image_url, price, currency, product_url,
  tags, promo_codes, deal_score, availability, restock_estimate, created_at, updated_at
) VALUES
${products.slice(i, i + BATCH).map(productRow).join(",\n")};`);
}

const historyChunks = [];
for (let i = 0; i < products.length; i += 40) {
  const slice = products.slice(i, i + 40);
  const rows = slice.flatMap((item) => {
    const peakBump = item.promoCodes[0]?.discountPercent >= 30 ? item.price * 1.12 : item.price * 1.04;
    return [
      `  (${sqlStr(item.id)}, ${peakBump.toFixed(2)}, datetime('now', '-14 days'))`,
      `  (${sqlStr(item.id)}, ${item.price.toFixed(2)}, datetime('now'))`,
    ];
  });
  historyChunks.push(`INSERT OR IGNORE INTO price_history (product_id, price, recorded_at) VALUES\n${rows.join(",\n")};`);
}

