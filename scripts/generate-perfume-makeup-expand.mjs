function unique(tags) {
  return [...new Set(tags.filter(Boolean))];
}

function brandTags(brand) {
  const lower = brand.toLowerCase();
  return unique([lower, ...lower.split(/[^a-z0-9]+/).filter((w) => w.length > 1)]);
}

function scentTags({ notes = [], kind = "edp", gender = "unisex", extra = [], brand }) {
  const kindTags = {
    edp: ["eau de parfum", "edp", "parfum"],
    edt: ["eau de toilette", "edt"],
    edc: ["eau de cologne", "edc", "cologne"],
    mist: ["body mist", "mist", "body", "fragrance mist"],
    travel: ["travel spray", "travel", "travel size", "eau de parfum", "edp"],
    gift: ["gift set", "gift", "set", "perfume gift"],
  };
  const genderTags =
    gender === "womens" ? ["womens", "women", "women's"] :
    gender === "mens" ? ["mens", "men", "men's"] :
    ["unisex"];
  const noteTags = notes.flatMap((note) => {
    const extras = [];
    if (note === "vanilla") extras.push("vanilla perfume", "gourmand");
    if (note === "oud") extras.push("oud perfume", "woody");
    if (note === "floral") extras.push("floral perfume");
    if (note === "woody") extras.push("woody perfume");
    if (note === "fresh") extras.push("fresh perfume");
    if (note === "gourmand") extras.push("gourmand perfume");
    return [note, ...extras];
  });
  return unique([
    "perfume", "fragrance",
    ...(kindTags[kind] || kindTags.edp),
    ...genderTags,
    ...noteTags,
    ...brandTags(brand),
    ...extra,
  ]);
}

function promo(code, label, discountPercent) {
  return [{ code, label, discountPercent }];
}

function p(id, name, brand, description, imageUrl, price, tags, promoCodes, dealScore, availability = "in_stock", restock = null) {
  return { id, name, brand, description, imageUrl, price, tags, promoCodes, dealScore, availability, restock };
}

function perfume(id, name, brand, description, price, notes, opts = {}) {
  const kind = opts.kind ?? "edp";
  const gender = opts.gender ?? "unisex";
  const extra = opts.extra ?? [];
  const imageUrl = opts.image ?? nextPerfumeImg();
  const tags = scentTags({ notes, kind, gender, extra, brand });
  return p(id, name, brand, description, imageUrl, price, tags, opts.promo ?? [], opts.score ?? 72, opts.availability, opts.restock);
}

/** Color + category phrase tags so "pink blush" / "nude lipstick" / "deep foundation" match. */
function colorCatTags(category, colors, extras = []) {
  const phrases = colors.flatMap((color) => [color, `${color} ${category}`]);
  return unique([category, "makeup", ...phrases, ...extras]);
}

function lipItem(id, name, brand, description, imageUrl, price, colors, finish, extras, promoCodes, dealScore) {
  const kind = extras.includes("gloss") ? "lip gloss" : extras.includes("liner") ? "lip liner" : "lipstick";
  const tags = unique([
    ...colorCatTags("lipstick", colors, extras),
    kind,
    "lips",
    finish,
    `${finish} lipstick`,
    ...brandTags(brand),
    ...colors.map((c) => `${c} ${kind}`),
  ]);
  return p(id, name, brand, description, imageUrl, price, tags, promoCodes, dealScore);
}

function blushItem(id, name, brand, description, imageUrl, price, colors, extras, promoCodes, dealScore) {
  return p(id, name, brand, description, imageUrl, price, unique([...colorCatTags("blush", colors, extras), ...brandTags(brand)]), promoCodes, dealScore);
}

function baseItem(category, id, name, brand, description, imageUrl, price, depth, undertone, extras, promoCodes, dealScore) {
  const tags = unique([
    category, "makeup", depth, undertone,
    `${depth} ${category}`, `${undertone} ${category}`,
    `${depth} ${undertone}`, extras.includes("matte") ? `matte ${category}` : null,
    ...extras, ...brandTags(brand),
  ]);
  return p(id, name, brand, description, imageUrl, price, tags, promoCodes, dealScore);
}

function nailItem(id, name, brand, description, imageUrl, price, colors, extras, promoCodes, dealScore) {
  return p(
    id, name, brand, description, imageUrl, price,
    unique(["nails", "nail", "polish", "nail polish", "manicure", ...colorCatTags("nail", colors, extras), ...brandTags(brand)]),
    promoCodes, dealScore,
  );
}

function serumItem(id, name, brand, description, imageUrl, price, actives, extras, promoCodes, dealScore) {
  const activeTags = actives.flatMap((a) => [a, `${a} serum`]);
  return p(
    id, name, brand, description, imageUrl, price,
    unique(["serum", "skincare", ...activeTags, ...extras, ...brandTags(brand)]),
    promoCodes, dealScore,
  );
}

